function findLongitude(place) {
  const text = String(place || "").trim();
  if (!text) return null;
  let matched = null;
  for (let index = 0; index < CITIES.length; index += 1) {
    const item = CITIES[index];
    if (text.indexOf(item[0]) >= 0) {
      if (!matched || item[0].length > matched[0].length) matched = item;
    }
  }
  return matched ? matched[1] : null;
}

